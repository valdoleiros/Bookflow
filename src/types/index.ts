// ============================================================
// BookFlow – shared TypeScript types
// ============================================================

export type BookingStatus = 'confirmed' | 'cancelled' | 'completed' | 'no_show'
export type NotificationType = 'confirmation' | 'reminder_24h' | 'reminder_2h'
export type NotificationStatus = 'pending' | 'sent' | 'failed'
export type NotificationChannel = 'email' | 'sms'

export interface Business {
  id: string
  name: string
  email: string
  phone: string | null
  slug: string
  timezone: string
  created_at: string
}

export interface Service {
  id: string
  business_id: string
  name: string
  duration_minutes: number
  price: number | null
  is_active: boolean
  created_at: string
}

export interface Availability {
  id: string
  business_id: string
  staff_id: string | null
  day_of_week: number // 0=Sun … 6=Sat
  start_hour: string  // "09:00"
  end_hour: string    // "19:00"
  is_active: boolean
}

export interface Customer {
  id: string
  name: string
  phone: string
  email: string | null
  created_at: string
}

export interface Booking {
  id: string
  business_id: string
  service_id: string
  customer_id: string
  staff_id: string | null
  start_time: string  // ISO
  end_time: string    // ISO
  status: BookingStatus
  reminder_sent: boolean
  notes: string | null
  created_at: string
}

export interface BookingWithDetails extends Booking {
  service: Service
  customer: Customer
  business: Business
}

export interface Notification {
  id: string
  booking_id: string
  type: NotificationType
  channel: NotificationChannel
  scheduled_time: string
  sent_at: string | null
  status: NotificationStatus
  error_message: string | null
  created_at: string
}

// ── Slot generated by slot-engine ─────────────────────────
export interface TimeSlot {
  start: string  // ISO
  end: string    // ISO
  available: boolean
}

// ── Public booking page data bundle ──────────────────────
export interface BookingPageData {
  business: Business
  services: Service[]
}

// ── Booking creation request ──────────────────────────────
export interface CreateBookingRequest {
  business_id: string
  service_id: string
  staff_id?: string | null
  start_time: string
  customer_name: string
  customer_phone: string
  customer_email?: string
}

export interface CreateBookingResponse {
  booking_id: string
  message: string
}

// ── Dashboard data bundle ─────────────────────────────────
export interface DashboardData {
  todayBookings: BookingWithDetails[]
  upcomingBookings: BookingWithDetails[]
}